#!/usr/bin/env python3
"""
bundle_prompt.py: 将规范文档打包编译为单文件 System Prompt。
用于不支持多文件路由的轻量 AI 工具（如 ChatGPT Web, Claude Projects, API 注入）。
支持参数: python3 bundle_prompt.py [all|cpp|ue5|web|python]
"""

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent

DOMAIN_MAP = {
    "cpp": ["00-行为规范", "10-通用代码规范", "20-CPP规范", "40-协作规范", "50-审查规范"],
    "ue5": ["00-行为规范", "10-通用代码规范", "20-CPP规范", "30-UE5规范", "40-协作规范", "50-审查规范"],
    "web": ["00-行为规范", "10-通用代码规范", "60-Web前端规范", "40-协作规范", "50-审查规范"],
    "python": ["00-行为规范", "10-通用代码规范", "70-Python工程规范", "40-协作规范", "50-审查规范"],
    "all": ["00-行为规范", "10-通用代码规范", "20-CPP规范", "30-UE5规范", "60-Web前端规范", "70-Python工程规范", "40-协作规范", "50-审查规范"]
}

def bundle(domain: str) -> Path:
    target_domains = DOMAIN_MAP.get(domain, DOMAIN_MAP["all"])
    output_file = REPO_ROOT / f"SYSTEM_PROMPT_{domain.upper()}.md"

    buffer = []
    buffer.append(f"# AI Master System Prompt (Bundled Profile: {domain.upper()})\n")
    buffer.append("> Auto-generated by scripts/bundle_prompt.py. Do not edit directly.\n\n---\n")

    # 1. 挂载主网关
    agents_md = REPO_ROOT / "AGENTS.md"
    if agents_md.exists():
        buffer.append(f"\n<!-- BUNDLE: AGENTS.md -->\n")
        buffer.append(agents_md.read_text(encoding="utf-8"))
        buffer.append("\n\n---\n")

    # 2. 依次挂载对应域文件
    guidelines_dir = REPO_ROOT / "guidelines"
    for d_name in target_domains:
        d_path = guidelines_dir / d_name
        if not d_path.exists():
            continue
        md_files = sorted(d_path.glob("*.md"))
        for f in md_files:
            buffer.append(f"\n<!-- BUNDLE: {d_name}/{f.name} -->\n")
            buffer.append(f.read_text(encoding="utf-8"))
            buffer.append("\n\n---\n")

    output_file.write_text("\n".join(buffer), encoding="utf-8")
    print(f"📦 成功打包 [{domain}] 专属单文件提示词: {output_file.name} ({len(buffer)} 块)")
    return output_file

if __name__ == "__main__":
    profile = sys.argv[1].lower() if len(sys.argv) > 1 else "cpp"
    bundle(profile)

